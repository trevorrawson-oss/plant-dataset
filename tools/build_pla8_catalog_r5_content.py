def apply_round(data):
    """Mint two methods, mint one source, widen two methods. Returns a summary dict.

    Raises rather than silently no-opping: a mint that already exists or a widening whose target is
    already present means the base is not what this round was written against.
    """
    cm = data["control_methods"]
    sc = data["source_catalog"]

    for key in MINTS:
        if key in cm:
            raise AssertionError(f"{key} is already in the catalog")
    for sid in NEW_SOURCES:
        if sid in sc:
            raise AssertionError(f"source id {sid} is already in source_catalog")
    for key, w in WIDENINGS.items():
        if key not in cm:
            raise AssertionError(f"{key} is not in the catalog, so it cannot be widened")
        already = set(cm[key].get("applies_to") or []) & set(w["add_applies_to"])
        if already:
            raise AssertionError(f"{key} already applies to {sorted(already)}")

    for sid, entry in NEW_SOURCES.items():
        sc[sid] = dict(entry)
    for key, method in MINTS.items():
        cm[key] = dict(method)

    for key, w in WIDENINGS.items():
        m = cm[key]
        m["applies_to"] = list(m["applies_to"]) + list(w["add_applies_to"])
        m["sources"] = list(m["sources"]) + [s for s in w["add_sources"] if s not in m["sources"]]
        anchors = dict(m["anchoring_urls"])
        for sid, a in w["add_anchoring_urls"].items():
            # NEVER overwrite: anchoring_urls allows one URL per source id, and clobbering the
            # existing anchor would silently drop the document the method was originally built on.
            if sid in anchors:
                raise AssertionError(f"{key}: anchoring_urls already has {sid}; widening must add, "
                                     f"never overwrite")
            anchors[sid] = dict(a)
        m["anchoring_urls"] = anchors
        for field, value in w["prose"].items():
            if field not in m:
                raise AssertionError(f"{key}: prose field {field!r} is not on the existing method")
            m[field] = list(value) if isinstance(value, list) else value

    return {"minted": sorted(MINTS), "widened": sorted(WIDENINGS), "sources": sorted(NEW_SOURCES)}


